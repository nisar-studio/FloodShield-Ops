/**
 * FloodShield Ops - Automated Incident Briefing Exporter
 * Generates an executive decision-support dossier for city control room leadership.
 */

export function exportIncidentReport({
  scenario,
  hotspots = [],
  facilities = [],
  currentRun = {},
  auditEntries = [],
}) {
  const plan = currentRun?.plan || {};
  const simulation = currentRun?.simulation || {};
  const timestamp = new Date().toISOString();

  const report = `# FLOODSHIELD OPS // CITY CONTROL ROOM OPERATIONAL DOSSIER
Generated: ${timestamp}
Pilot Area: ${scenario?.areaName || 'Bengaluru - Mahadevapura Corridor'}
Scenario ID: ${scenario?.scenarioId || 'N/A'} (Mode: ${scenario?.mode || 'replay'})

================================================================================
1. METEOROLOGICAL TELEMETRY
================================================================================
- Total Precipitation: ${scenario?.rainfall?.totalMm || 0} mm over ${scenario?.rainfall?.durationHours || 0} hours
- Hourly Profile (mm): [${(scenario?.rainfall?.hourlyMm || []).join(', ')}]
- Source: ${scenario?.source || 'KSNDMC Radar Telemetry'}

================================================================================
2. CRITICAL FLOOD HOTSPOTS IDENTIFIED (${hotspots.length})
================================================================================
${hotspots
  .map(
    (hs, i) => `${i + 1}. [${hs.id}] ${hs.name}
   - Calculated Risk Score: ${(hs.riskScore || 0).toFixed(2)} / 1.00
   - Contributing Factors: ${(hs.reasons || []).join('; ')}
   - Inundated Edges: ${(hs.floodedEdgeIds || []).join(', ')}`
  )
  .join('\n\n')}

================================================================================
3. AI PLANNER MITIGATING CANDIDATE ACTIONS (${plan.actions?.length || 0})
================================================================================
Plan ID: ${plan.planId || 'N/A'} (Iteration ${plan.iteration || 1})
Status: ${plan.status || 'N/A'}

${(plan.actions || [])
  .map(
    (act, i) => `${i + 1}. [${act.actionId}] ${act.type.toUpperCase()}: ${act.target?.label || 'Target'}
   - Rationale: ${act.rationale}
   - Evidence Basis: ${(act.evidence || []).join(', ')}
   - AI Confidence: ${typeof act.confidence === 'number' ? (act.confidence * 100).toFixed(0) + '%' : 'N/A'}`
  )
  .join('\n\n')}

================================================================================
4. DETERMINISTIC REACHABILITY VERIFICATION (T = 30 MIN)
================================================================================
- Baseline Reachability (Do Nothing): ${((simulation.baselineScore || 0) * 100).toFixed(1)}%
- With Proposed Plan: ${((simulation.planScore || 0) * 100).toFixed(1)}%
- Minimum Required Safety Threshold: ${((simulation.threshold || 0) * 100).toFixed(1)}%
- VERIFIER VERDICT: ${simulation.passed ? 'PASSED & APPROVED FOR OPERATOR GATE' : 'FAILED - REPLAN REQUIRED'}

Critical Facility Transit Times:
${(simulation.perFacility || [])
  .map(
    (f) => `   * ${f.name || f.facilityId}: Baseline=${f.reachableBefore ? f.minutesBefore + 'm' : 'SEVERED'} -> Plan=${f.reachableAfter ? f.minutesAfter + 'm' : 'UNREACHABLE'}`
  )
  .join('\n')}

================================================================================
5. HUMAN OPERATOR AUTHORIZATION GATE
================================================================================
- Gate Status: ${plan.status === 'approved' || plan.status === 'executed_sandbox' ? 'AUTHORIZED BY OPERATOR' : 'PENDING / LOCKED'}
- Sandbox Execution: Simulated only. Non-destructive sandbox testbed.

================================================================================
6. AUDIT TRAIL LOG (${auditEntries.length} EVENTS)
================================================================================
${auditEntries
  .map((e) => `[${e.ts}] [${e.actor.toUpperCase()}] ${e.event} - Payload: ${JSON.stringify(e.payload)}`)
  .join('\n')}

================================================================================
Notice: Generated by FloodShield Ops Decision-Support System. Decision-support only.
`;

  // Trigger browser download
  const blob = new Blob([report], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `floodshield-ops-dossier-${scenario?.scenarioId || 'run'}-${Date.now()}.md`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
